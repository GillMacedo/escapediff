func runCmd(args ...string) (int, string, string) {
	var out, errb bytes.Buffer
	code := run(args, &out, &errb)
	return code, out.String(), errb.String()
}

func TestRunExitCodes(t *testing.T) {
	before, after, comments := logPath("shop-before.log"), logPath("shop-after.log"), logPath("shop-comments.log")
	if code, _, _ := runCmd("compare", before, after); code != 0 {
		t.Errorf("without --fail: %d", code)
	}
	if code, _, _ := runCmd("compare", "--fail", before, after); code != 1 {
		t.Errorf("--fail with regressions: %d", code)
	}
	if code, _, _ := runCmd("compare", "--fail", before, comments); code != 0 {
		t.Errorf("--fail without changes: %d", code)
	}
	if code, out, _ := runCmd("compare", "--json", before, after); code != 0 || !strings.Contains(out, `"noLongerInlined"`) {
		t.Errorf("--json: %d %s", code, out)
	}
	if code, _, _ := runCmd("compare", before); code != 2 {
		t.Errorf("missing arg: %d", code)
	}
	if code, _, _ := runCmd("compare", before, "nope.log"); code != 2 {
		t.Errorf("missing file: %d", code)
	}
	if code, _, _ := runCmd("bogus"); code != 2 {
		t.Errorf("unknown command: %d", code)
	}
	if code, out, _ := runCmd("version"); code != 0 || out != "escapediff "+version+"\n" {
		t.Errorf("version: %d %q", code, out)
	}
	empty := filepath.Join(t.TempDir(), "empty.log")
	os.WriteFile(empty, []byte("ok  \texample.com/p\n"), 0o644)
	// A failed build must never read as every escape having gone away.
	dir := t.TempDir()
	real, failed := filepath.Join(dir, "real.log"), filepath.Join(dir, "failed.log")
	os.WriteFile(real, []byte("./a.go:3:9: x escapes to heap\n./a.go:5:9: moved to heap: y\n"), 0o644)
	os.WriteFile(failed, []byte("# example.com/x\n./main.go:3:9: syntax error: unexpected {\n"), 0o644)
	for _, pair := range [][]string{{real, failed}, {failed, real}, {real, empty}, {empty, real}} {
		if code, out, errs := runCmd("compare", "--fail", pair[0], pair[1]); code != 2 || !strings.Contains(errs, "failed build") {
			t.Errorf("%v: %d %s %s", pair, code, out, errs)
		}
	}
	if code, _, errs := runCmd("compare", empty, empty); code != 2 || !strings.Contains(errs, "-gcflags=-m=2") {
		t.Errorf("empty logs: %d %s", code, errs)
	}
}

func TestUntarRejectsEscapes(t *testing.T) {
	for _, name := range []string{"../evil.go", "/abs.go", "a/../../evil.go"} {
		var buf bytes.Buffer
		tw := tar.NewWriter(&buf)
		tw.WriteHeader(&tar.Header{Name: name, Mode: 0o644, Size: 1, Typeflag: tar.TypeReg})
		tw.Write([]byte("x"))
		tw.Close()
		if err := untar(&buf, t.TempDir()); err == nil {
			t.Errorf("%s: no error", name)
		}
	}
	var buf bytes.Buffer
	tw := tar.NewWriter(&buf)
	tw.WriteHeader(&tar.Header{Name: "link", Linkname: "/etc", Typeflag: tar.TypeSymlink})
	tw.WriteHeader(&tar.Header{Name: "d/f.go", Mode: 0o644, Size: 2, Typeflag: tar.TypeReg})
	tw.Write([]byte("ok"))
	tw.Close()
	dir := t.TempDir()
	if err := untar(&buf, dir); err != nil {
		t.Fatal(err)
	}
	if _, err := os.Lstat(filepath.Join(dir, "link")); err == nil {
		t.Error("symlink was created")
	}
	if b, _ := os.ReadFile(filepath.Join(dir, "d", "f.go")); string(b) != "ok" {
		t.Error("regular file not written")
	}
}
