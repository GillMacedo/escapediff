func TestShopChange(t *testing.T) {
	r := compareLogs(t, "shop-before.log", "shop-after.log", false)
	if r.ByFile {
		t.Fatal("both logs are -m=2")
	}
	wantHeap := []string{
		`FormatID: "ord-" + ~r0 escapes to heap`,
		"ParseQuantity: &errors.errorString{...} escapes to heap",
		"ParseQuantity: s escapes to heap",
	}
	if got := texts(r.NewHeap); strings.Join(got, "|") != strings.Join(wantHeap, "|") {
		t.Errorf("new heap = %q", got)
	}
	if len(r.LostInline) != 2 || r.LostInline[0].Name != "(*Order).Total" || r.LostInline[0].CallSites != 2 ||
		r.LostInline[0].BaseCost != 53 || r.LostInline[0].Cost != 116 || r.LostInline[1].Name != "ParseQuantity" {
		t.Errorf("lost inline = %+v", r.LostInline)
	}
	if g := r.LostInline[0].Grown; len(g) != 2 || g[1].Name != "roundCents" || g[1].BaseCost != 6 || g[1].Cost != 36 {
		t.Errorf("grown callees = %+v", g)
	}
	wantLeaks := []string{"Receipt: leaking param: o", "Batch: leaking param content: orders", "(*Order).Total: leaking param: o", "ParseQuantity: leaking param: s"}
	if got := texts(r.NewLeaks); strings.Join(got, "|") != strings.Join(wantLeaks, "|") {
		t.Errorf("new leaks = %q", got)
	}
	if len(r.LostDevirt) != 1 || r.LostDevirt[0].Func != "Receipt" {
		t.Errorf("lost devirt = %+v", r.LostDevirt)
	}
	if len(r.GoneHeap) != 1 || r.GoneHeap[0].Text != "id escapes to heap" {
		t.Errorf("gone heap = %+v", r.GoneHeap)
	}
	if len(r.NearBudget) != 2 || r.NearBudget[0].Name != "Batch" || r.NearBudget[1].Name != "FormatID" {
		t.Errorf("near budget = %+v", r.NearBudget)
	}
	if r.Regressions() != 10 {
		t.Errorf("regressions = %d", r.Regressions())
	}
}

