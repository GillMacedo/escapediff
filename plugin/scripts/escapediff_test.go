func logPath(name string) string {
	return filepath.Join("..", "..", "examples", "logs", name)
}

func mustParse(t *testing.T, name string) *Build {
	t.Helper()
	b, err := parseFile(logPath(name))
	if err != nil {
		t.Fatal(err)
	}
	return b
}

func compareLogs(t *testing.T, base, head string, all bool) *Result {
	t.Helper()
	return Compare(mustParse(t, base), mustParse(t, head), all)
}

func texts(ds []Diag) []string {
	var out []string
	for _, d := range ds {
		out = append(out, d.Func+": "+d.Text)
	}
	return out
}

func TestParseDetailed(t *testing.T) {
	log := `# example.com/p
2026-11-02T10:00:00.1234567Z p/p.go:7:6: can inline round with cost 8 as: func(int) int { return x }
p/p.go:9:6: cannot inline Big: function too complex: cost 95 exceeds budget 80
p/p.go:12:14: can inline Big.func1 with cost 3 as: func() { n++ }
p/p.go:20:6: can inline Map[go.shape.int] with cost 4 as: func() {}
p/p.go:20:6: can inline Map[int] with cost 10 as: func() {}
p/p.go:10:13: inlining call to round
p/p.go:13:2: x escapes to heap in Big:
p/p.go:13:2:   flow: ~r0 = &x:
p/p.go:13:2:     from &x (address-of) at p/p.go:14:9
p/p.go:13:2: moved to heap: x
p/p.go:15:10: append(buf, s...) escapes to heap in Big:
p/p.go:15:10: append escapes to heap
p/p.go:9:10: parameter s leaks to {heap} for Big with derefs=0:
p/p.go:9:10: leaking param: s
p/p.go:9:20: buf does not escape
p/p.go:21:3: devirtualizing i.M to T
<autogenerated>:1: inlining call to T.M
`
	b, err := Parse(strings.NewReader(log))
	if err != nil {
		t.Fatal(err)
	}
	if !b.Detailed || b.Packages != 1 || b.Budget != 80 {
		t.Fatalf("detailed=%v packages=%d budget=%d", b.Detailed, b.Packages, b.Budget)
	}
	want := []string{
		"Big: round",
		"Big: moved to heap: x",
		"Big: append escapes to heap",
		"Big: leaking param: s",
		"Map: devirtualizing i.M to T",
	}
	if got := texts(b.Diags); strings.Join(got, "\n") != strings.Join(want, "\n") {
		t.Fatalf("diags:\n%s\nwant:\n%s", strings.Join(got, "\n"), strings.Join(want, "\n"))
	}
	if d := b.Diags[2].Detail; d != "append(buf, s...) escapes to heap" {
		t.Errorf("detail = %q", d)
	}
	if d := b.Diags[1].Detail; d != "" {
		t.Errorf("moved to heap should keep its own text, got detail %q", d)
	}
	if why := strings.Join(b.Diags[1].Why, "\n"); !strings.Contains(why, "flow: ~r0 = &x:") {
		t.Errorf("moved to heap should get its flow lines, got %q", b.Diags[1].Why)
	}
	big := b.Funcs["p|Big"]
	if big == nil || big.Inlinable || big.Cost != 95 || !strings.Contains(big.Reason, "exceeds budget") {
		t.Errorf("Big = %+v", big)
	}
	m := b.Funcs["p|Map"]
	if m == nil || !m.Inlinable || m.Cost != 10 {
		t.Errorf("generic Map should be one inlinable function with the larger cost, got %+v", m)
	}
	if b.Funcs["p|Big.func1"] == nil {
		t.Error("closure should be recorded as a function")
	}
	if b.HeapCount() != 2 || b.InlinableCount() != 3 {
		t.Errorf("heap=%d inlinable=%d", b.HeapCount(), b.InlinableCount())
	}
}

func TestParseWhySeparatesEscapesAtOnePosition(t *testing.T) {
	log := `# example.com/p
p/p.go:1:1: first escapes to heap in F:
p/p.go:1:1:   flow: {heap} ← &first:
p/p.go:1:1:     from first (spill) at p/p.go:1:1
p/p.go:1:1: append(a, b...) escapes to heap in F:
p/p.go:1:1:   flow: slices.s ← &{storage for append(a, b...)}:
p/p.go:1:1:     from append(a, b...) (spill) at p/p.go:1:1
p/p.go:1:1: append(c, d...) escapes to heap in F:
p/p.go:1:1:   flow: slices.s ← &{storage for append(c, d...)}:
p/p.go:1:1:     from append(c, d...) (spill) at p/p.go:1:1
p/p.go:1:1: first escapes to heap
p/p.go:1:1: append escapes to heap
p/p.go:1:1: append escapes to heap
`
	b, err := Parse(strings.NewReader(log))
	if err != nil {
		t.Fatal(err)
	}
	if len(b.Diags) != 3 {
		t.Fatalf("got %d diagnostics: %v", len(b.Diags), texts(b.Diags))
	}
	checks := []struct {
		contains string
		misses   string
	}{
		{"flow: {heap} ← &first:", "append("},
		{"storage for append(a, b...)", "first"},
		{"storage for append(c, d...)", "first"},
	}
	for i, c := range checks {
		why := strings.Join(b.Diags[i].Why, "\n")
		if !strings.Contains(why, c.contains) {
			t.Errorf("diag %d %q misses %q", i, why, c.contains)
		}
		if strings.Contains(why, c.misses) {
			t.Errorf("diag %d %q also has %q", i, why, c.misses)
		}
	}
}

